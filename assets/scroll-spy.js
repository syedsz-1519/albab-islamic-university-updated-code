// Scroll Spy Indicator
// Desktop-only (1024px+), fixed right sidebar with circular progress ring and section dots
// Uses IntersectionObserver (no scroll listeners)

(function() {
  // Only show on desktop (1024px+)
  const mediaQuery = window.matchMedia('(min-width: 1024px)');
  
  if (!mediaQuery.matches) return;

  // Section IDs to track (must exist in HTML)
  const SECTIONS = ['hero', 'hadith-section', 'focus', 'programmes-preview', 'founder-section', 'contact-strip'];

  // Create scroll spy indicator HTML
  const indicator = document.createElement('div');
  indicator.id = 'scroll-spy-indicator';
  indicator.innerHTML = `
    <div class="scroll-spy-ring" role="region" aria-label="Scroll progress">
      <svg viewBox="0 0 100 100" width="60" height="60">
        <circle cx="50" cy="50" r="45" class="progress-track"></circle>
        <circle cx="50" cy="50" r="45" class="progress-fill"></circle>
      </svg>
      <button class="scroll-to-top" aria-label="Scroll to top" title="Back to top">↑</button>
    </div>
    <div class="scroll-spy-dots" role="navigation" aria-label="Page sections">
      <!-- Generated by JS -->
    </div>
  `;
  document.body.appendChild(indicator);

  // Generate dot buttons
  function generateDots() {
    const dotsContainer = document.querySelector('.scroll-spy-dots');
    SECTIONS.forEach((sectionId, i) => {
      const section = document.getElementById(sectionId);
      if (section) {
        const dot = document.createElement('button');
        dot.className = 'scroll-spy-dot';
        dot.setAttribute('data-section', sectionId);
        dot.setAttribute('aria-label', `Go to section ${i + 1}`);
        dot.title = section.querySelector('h1, h2')?.textContent || `Section ${i + 1}`;
        dot.addEventListener('click', () => {
          section.scrollIntoView({ behavior: 'smooth' });
        });
        dotsContainer.appendChild(dot);
      }
    });
  }

  // Initialize IntersectionObserver
  function initIntersectionObserver() {
    const dots = document.querySelectorAll('.scroll-spy-dot');
    
    const options = {
      root: null,
      rootMargin: '-50% 0px -50% 0px',
      threshold: 0
    };

    const observer = new IntersectionObserver((entries) => {
      entries.forEach(entry => {
        const dot = document.querySelector(`.scroll-spy-dot[data-section="${entry.target.id}"]`);
        if (dot) {
          if (entry.isIntersecting) {
            dots.forEach(d => d.classList.remove('active'));
            dot.classList.add('active');
          }
        }
      });
    }, options);

    // Observe sections
    SECTIONS.forEach(sectionId => {
      const section = document.getElementById(sectionId);
      if (section) {
        observer.observe(section);
      }
    });
  }

  // Update progress ring
  function updateProgressRing() {
    const scrollTop = window.scrollY || document.documentElement.scrollTop;
    const docHeight = document.documentElement.scrollHeight - window.innerHeight;
    const scrolled = docHeight > 0 ? (scrollTop / docHeight) * 100 : 0;

    const progressFill = document.querySelector('.progress-fill');
    if (progressFill) {
      const circumference = 2 * Math.PI * 45; // radius 45
      const offset = circumference - (scrolled / 100) * circumference;
      progressFill.style.strokeDashoffset = offset;
    }
  }

  // Scroll to top button
  function initScrollToTop() {
    const btn = document.querySelector('.scroll-to-top');
    if (btn) {
      btn.addEventListener('click', () => {
        // Check prefers-reduced-motion
        const prefersReduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
        window.scrollTo({
          top: 0,
          behavior: prefersReduced ? 'auto' : 'smooth'
        });
      });
    }
  }

  // Keyboard navigation on dots
  function initKeyboardNav() {
    const dots = document.querySelectorAll('.scroll-spy-dot');
    dots.forEach((dot, i) => {
      dot.addEventListener('keydown', (e) => {
        if (e.key === 'ArrowDown' || e.key === 'ArrowRight') {
          e.preventDefault();
          const next = dots[(i + 1) % dots.length];
          next.focus();
          next.click();
        } else if (e.key === 'ArrowUp' || e.key === 'ArrowLeft') {
          e.preventDefault();
          const prev = dots[(i - 1 + dots.length) % dots.length];
          prev.focus();
          prev.click();
        }
      });
    });
  }

  // Respect prefers-reduced-motion
  function checkReducedMotion() {
    const prefersReduced = window.matchMedia('(prefers-reduced-motion: reduce)').matches;
    const indicator = document.getElementById('scroll-spy-indicator');
    if (prefersReduced) {
      indicator.classList.add('reduce-motion');
    }
  }

  // Initialize on DOM ready
  if (document.readyState === 'loading') {
    document.addEventListener('DOMContentLoaded', init);
  } else {
    init();
  }

  function init() {
    generateDots();
    initIntersectionObserver();
    initScrollToTop();
    initKeyboardNav();
    checkReducedMotion();
    updateProgressRing();
    
    // Update progress on scroll (debounced)
    let scrollTimeout;
    window.addEventListener('scroll', () => {
      clearTimeout(scrollTimeout);
      scrollTimeout = setTimeout(updateProgressRing, 50);
    });
  }

  // Handle window resize (hide/show on desktop toggle)
  window.addEventListener('resize', () => {
    const isDesktop = window.matchMedia('(min-width: 1024px)').matches;
    const indicator = document.getElementById('scroll-spy-indicator');
    if (indicator) {
      indicator.style.display = isDesktop ? 'flex' : 'none';
    }
  });
})();
